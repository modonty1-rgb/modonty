/**
 * سطرٌ عربيّ يبدأ بنصّ لاتيني (بريد · رابط) **يُقلب ترتيبه** على أندرويد.
 *
 * اتّجاه الفقرة يُؤخذ من أوّل حرف «قويّ»: «modonty1@gmail.com · من مقال: …» يبدأ بحرف لاتيني،
 * فتُرسم الفقرة يساراً‑ليمين ويقفز البريد إلى الطرف الأيسر بعد المقال — قِيس على جوّال خالد
 * في «الرد على سؤال». `writingDirection: 'rtl'` لا يكفي لأنّ أندرويد يحسم الاتّجاه من النصّ.
 *
 * العلاج المعياري (Unicode UAX #9): عزل السطر كلّه في اتّجاه عربي بـRLI…PDI، وقبله RLM
 * يثبّت أوّل حرف قويّ لمحرّكات لا تقرأ العزل. البريد داخله يبقى كتلة لاتينية سليمة.
 */
const RLM = '‏';
const RLI = '⁧';
const PDI = '⁩';

export function rtlLine(text: string): string {
  return `${RLM}${RLI}${text}${PDI}`;
}

const LRM = '‎';
const LRI = '⁦';

/**
 * العكس: قيمة لاتينية وحدها (رقم جوال · بريد) داخل عنصر عربي الاتّجاه. «+99900000002» بلا حرف
 * قويّ يُرسم «99900000002+» في فقرة RTL؛ العزل LRI…PDI يبقيه كما يُكتب.
 */
export function ltrLine(text: string): string {
  return `${LRM}${LRI}${text}${PDI}`;
}
