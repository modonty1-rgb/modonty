import { z } from "zod";

/**
 * **قاعدةٌ واحدةٌ لكلمة مرور القارئ — في كلّ باب.**
 *
 * خالد (٢٠ سبتمبر ٢٠٢٦): «ثمانية حروف مرّة كثيرة، سهّلها».
 *
 * ── لماذا وُجد هذا الملفّ ──
 * كانت للمستخدم الواحد **ثلاث قواعد متناقضة**: التسجيل يقبل الستّ، وإعادةُ التعيين
 * تطلب ثماني، والإعداداتُ تطلب ثماني + حرفاً كبيراً وصغيراً ورقماً. فمَن سجّل بـ
 * `abcdef` لا يستطيع تغييرَ كلمته أبداً إلا بكلمةٍ تخالف ما قُبل منه يوم سجّل — بابٌ
 * يقبل ما يرفضه الآخر لنفس الحساب.
 *
 * ── ولماذا بلا شروط تركيب ──
 * NIST SP 800-63B توصي صراحةً بعدم فرض قواعد التركيب (حرف كبير/رقم/رمز)، لأنّها تدفع
 * الناس إلى أنماطٍ متوقَّعة (`Password1!`) وإلى إعادة استعمال الكلمة نفسها في كلّ موقع.
 * والطولُ وحده هو ما يُعتدّ به.
 *
 * ── وما لم نتبعه من التوصية ──
 * نفسُ الوثيقة توصي بثماني محارفَ حدّاً أدنى، وخالد اختار ستّاً لأنّ هذا حسابُ قارئٍ
 * يعلّق على مقال، لا لوحةَ تحكّم. وموظّفو الأدمن في `Staff` ولهم بابُهم وقواعدُهم.
 * فالقرارُ مذكورٌ هنا بمصدره كي يُراجَع بعلم، لا يُكتشف بالصدفة.
 */
export const PASSWORD_MIN = 6;

export const PASSWORD_HINT = `${PASSWORD_MIN} أحرف على الأقل`;

export const passwordField = z
  .string()
  .min(PASSWORD_MIN, `كلمة المرور يجب أن تكون ${PASSWORD_MIN} أحرف على الأقل`);
