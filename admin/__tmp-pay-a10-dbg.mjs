import { chromium } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
const db = new PrismaClient(); const BASE = 'http://localhost:3001';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, storageState: 'C:/tmp/pay-a1-evidence/state.json' });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message.slice(0, 300)));
page.on('response', async (r) => { if (r.request().method() === 'POST') console.log('POST', r.status(), r.url().slice(-40), (await r.text().catch(() => '')).slice(0, 200).replace(/\n/g, ' ')); });
await page.goto(`${BASE}/commercial-plans`, { waitUntil: 'load', timeout: 90000 }); await page.waitForSelector('main');
await page.locator('summary:has-text("إضافة باقة جديدة")').click(); await page.waitForTimeout(300);
console.log('name inputs visible:', await page.locator('input[name=name]:visible').count());
await page.locator('input[name=name]:visible').first().fill('باقة اختبار A10');
await page.fill('input[name=sa]', '599'); await page.fill('input[name=eg]', '2999'); await page.fill('input[name=articlesPerMonth]', '6');
await page.locator('button:has-text("إنشاء مسودة")').click();
await page.waitForTimeout(4000);
console.log('db:', JSON.stringify(await db.commercialPlan.findFirst({ where: { name: 'باقة اختبار A10' }, select: { id: true, slug: true } })));
await browser.close(); await db.$disconnect();
