import { chromium } from '@playwright/test';
const base = 'http://localhost:3001';
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1100 }, colorScheme: 'dark' })).newPage();
const msgs = [];
page.on('console', (m) => msgs.push(m.type() + ': ' + m.text().slice(0, 200)));
page.on('pageerror', (e) => msgs.push('PAGEERROR: ' + String(e).slice(0, 400)));
await page.goto(`${base}/login`, { waitUntil: 'networkidle' });
await page.fill('input[type="email"]', 'claude-check@modonty.local');
await page.fill('input[type="password"]', 'Mdnty-Local-Check-2026!');
await page.click('button[type="submit"]');
await page.waitForTimeout(5000);
await page.goto(base + '/playbook', { waitUntil: 'domcontentloaded', timeout: 180000 });
await page.waitForSelector('#system', { timeout: 60000 });
await page.waitForTimeout(4000);
const box = await page.locator('#system').boundingBox();
console.log('section box', box);
const inner = await page.locator('#system > div').first().boundingBox();
console.log('wrapper box', inner);
console.log('html', (await page.locator('#system').innerHTML()).slice(0, 600));
console.log('--- console ---');
console.log(msgs.slice(-25).join('\n'));
await browser.close();
