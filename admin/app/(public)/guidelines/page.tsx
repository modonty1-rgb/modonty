/**
 * The team guideline — ONE complete document, plain text.
 *
 * Everything the production team needs, in one scroll. Not a directory of cards, and not a
 * summary that points elsewhere: a new hire reads this top to bottom and can produce, and a
 * working writer scans it for the number they forgot.
 *
 * Every figure is the ENFORCED one, verified against the code that enforces it (validators,
 * the publish gate, the scorers). Three different limits for the SEO title were in circulation
 * before this rewrite, and the UI counter disagreed with the validator.
 *
 * Sales material is deliberately NOT here. Of the twenty "golden rules", sixteen are selling
 * lines — competitor rebuttals, packages, closing lines, objection handling. A writer never
 * uses them, and folding them in would rebuild exactly the bloat this document replaced.
 *
 * Style: Google developer-documentation guide — imperative voice, condition before
 * instruction, lists over prose, no metaphor and no motivational padding.
 */

function H2({ id, children }: { id: string; children: React.ReactNode }) {
  return (
    <h2 id={id} className="scroll-mt-6 border-b pb-1.5 pt-9 text-lg font-bold first:pt-0">
      {children}
    </h2>
  );
}

function H3({ children }: { children: React.ReactNode }) {
  return <h3 className="pt-5 text-sm font-bold">{children}</h3>;
}

function P({ children }: { children: React.ReactNode }) {
  return <p className="pt-2 text-[13px] leading-7 text-foreground/85">{children}</p>;
}

function UL({ children }: { children: React.ReactNode }) {
  return <ul className="list-disc space-y-1 pt-2 ps-5 text-[13px] leading-7 text-foreground/85">{children}</ul>;
}

function OL({ children }: { children: React.ReactNode }) {
  return <ol className="list-decimal space-y-1 pt-2 ps-5 text-[13px] leading-7 text-foreground/85">{children}</ol>;
}

function Table({ head, rows }: { head: string[]; rows: string[][] }) {
  return (
    <div className="overflow-x-auto pt-3">
      <table className="w-full text-[13px]">
        <thead>
          <tr className="border-b">
            {head.map((h) => (
              <th key={h} className="py-1.5 text-start font-bold">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r[0]} className="border-b border-border/40 last:border-0">
              {r.map((c, i) => (
                <td key={i} className="py-1.5 pe-4 align-top leading-6 text-foreground/85">
                  {c}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

