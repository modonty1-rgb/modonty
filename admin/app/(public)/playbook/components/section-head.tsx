/**
 * ترويسة قسم: عنوانٌ والسؤال الذي يجيب عنه.
 *
 * فقدت شيئين بطلب خالد (١٢ سبتمبر ٢٠٢٦):
 * · الرمز الإنجليزي في يسارها (BRAND-01 وأخواته) — «ما له داعي»، ومعه حُذف
 *   `components/reference.tsx` لأنه بقي بلا مستهلك.
 * · الرقم المربّع قبل العنوان — «خلاص هو سياق واحد حيمشي». وكان الترقيم يتكسّر
 *   أصلًا حين تُنقل صفحة من مكانها: صفحة الكتالوج كانت تبدأ وحدها بالقسم «٦».
 *
 * وحُذف خطّها السفليّ أيضًا، فكان يقع بينها وبين محتواها فاصلان: خطّها وحدّ البطاقة.
 *
 * و`hint` اختياريّ: القسم الذي يشرحه محتواه لا يحتاج سطرًا يشرحه فوقه.
 */
export function SectionHead({ title, hint }: { title: string; hint?: string }) {
  return (
    <div>
      <h2 className="text-[17px] font-bold leading-6">{title}</h2>
      {hint ? <p className="mt-1 text-[13px] leading-6 text-muted-foreground">{hint}</p> : null}
    </div>
  );
}
