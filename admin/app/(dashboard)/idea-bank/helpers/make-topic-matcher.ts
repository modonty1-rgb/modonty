/**
 * يقيس قرب نصٍّ (عنوان مقال · عبارة بحث) من موضوع فكرة: كم كلمةً مميِّزة من الموضوع وردت فيه.
 *
 * الكلمات العامة خارج العدّ — «السعودية» و«أفضل» و«دليل» في كل شيء، وعدّها يجعل كل مقالٍ «قريباً».
 * المطابقة بعد تطبيع الحروف (أ/إ/آ ← ا · ة ← ه · ى ← ي) لأن الكاتب والباحث لا يكتبانها سواء.
 */
const STOP = new Set(
  [
    "في", "من", "على", "عن", "الى", "الي", "مع", "او", "ما", "هو", "هي", "كيف", "افضل", "دليل", "شامل",
    "السعوديه", "السعودي", "سعودي", "سعوديه", "المملكه", "الجديد", "الجديده", "طريقه", "خطوات", "كل",
    "بين", "بعد", "قبل", "حسب", "لعام", "عام", "اهم", "جميع", "كامل", "الكامل", "اليوم", "الان",
  ].map((w) => w),
);

function norm(s: string): string {
  return s
    .toLowerCase()
    .replace(/[ًٌٍَُِّْـ]/g, "")
    .replace(/[إأآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/[^\p{L}\p{N}\s]/gu, " ");
}

/** يُرجع دالّةً تعطي لكل نص: عدد الكلمات المميِّزة المشتركة، وكم يلزم ليُعدّ قريباً. */
export function makeTopicMatcher(topic: string): { needed: number; score: (text: string) => number } {
  const words = [...new Set(norm(topic).split(/\s+/).filter((w) => w.length >= 3 && !STOP.has(w) && !/^\d+$/.test(w)))];
  // موضوعٌ بكلمةٍ مميِّزة واحدة يكفيه تطابقُها؛ وما زاد يحتاج كلمتين على الأقل.
  const needed = Math.min(2, words.length);
  return {
    needed,
    score: (text: string) => {
      if (words.length === 0) return 0;
      const t = ` ${norm(text)} `;
      // «ال» التعريف لا يفرّق: «الدوري» و«دوري» كلمة واحدة.
      return words.filter((w) => t.includes(` ${w} `) || t.includes(` ال${w.replace(/^ال/, "")} `) || t.includes(` ${w.replace(/^ال/, "")} `)).length;
    },
  };
}
