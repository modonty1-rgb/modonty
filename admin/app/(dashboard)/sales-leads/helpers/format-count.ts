/**
 * عددٌ بأرقام الشاشة نفسها — هندية لا لاتينية.
 *
 * كل تاريخٍ ومبلغ في هذه الشاشات يمرّ بـ`Intl` بلغة `ar-EG` فيخرج `٤ سبتمبر` و`٢٣٬٩٩٤`، بينما
 * العدّادات كانت تُطبع خامّاً: `التاريخ 3` جوار `٤ سبتمبر`، و`الإجمالي — 6 شهور` جوار
 * `٢٣٬٩٩٤ ج.م`. رقمان بأبجديتين في السطر الواحد يوقفان العين على غير معنى.
 *
 * والمُنسِّق يُبنى مرّة على مستوى الوحدة لا في كل رسمة: بناؤه ثمنٌ يُدفع بلا داعٍ في كل صفّ.
 */
const counter = new Intl.NumberFormat("ar-EG");

export function formatCount(n: number): string {
  return counter.format(n);
}
