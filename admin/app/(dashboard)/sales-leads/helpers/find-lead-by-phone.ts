import "server-only";

import { db } from "@/lib/db";

/**
 * آخر تسعة أرقام — المفتاح الذي يجعل الصيغ المختلفة رقماً واحداً.
 *
 * نفس الجوّال يصل مكتوباً `+201001234567` و`01001234567` و`0100 123 4567`. والمقارنة النصّية
 * تعتبرها ثلاثة أشخاص. وتسعةٌ لأنها تتجاوز الصفر ورمز الدولة في السوقين معاً:
 * مصر `01001234567` و`+201001234567` ⇒ `001234567` · السعودية `0501234567` و`+966501234567`
 * ⇒ `501234567`.
 */
export function phoneKey(phone: string): string {
  return phone.replace(/\D/g, "").slice(-9);
}

/**
 * هل هذا الرقم مسجَّل عند عميلٍ آخر؟ يرجع اسمه ومعرّفه، أو `null`.
 *
 * وُجد بالقياس: سجّلتُ «عيادة الأمل» برقم «دكتور محمد الشناوي» فحُفظ **بصمت** — صفّان بنفس
 * الجوّال. وهذا أسوأ من صفٍّ ناقص: مندوبتان تكلّمان الرجل نفسه، وتاريخه ينقسم نصفين فلا
 * يُقرأ من أيّهما ما قيل في المكالمة السابقة.
 *
 * `contains` لا عمودٌ مفهرس: الجدول عشرات الصفوف اليوم وآلافٌ في أسوأ حال، والمسح عليه أرخص
 * من عمودٍ ثانٍ للهاتف يجب أن يبقى متزامناً مع الأصل في كل مسار كتابة.
 */
export async function findLeadByPhone(
  phone: string,
  exceptId?: string,
): Promise<{ id: string; name: string } | null> {
  const key = phoneKey(phone);
  // أقلّ من تسعة رقماً ليس جوّالاً كاملاً، والبحث بجزءٍ قصير يطابق نصف الجدول.
  if (key.length < 9) return null;

  const rows = await db.salesLead.findMany({
    where: { phone: { contains: key }, ...(exceptId ? { id: { not: exceptId } } : {}) },
    select: { id: true, name: true, phone: true },
    take: 5,
  });

  // `contains` قد تطابق رقماً أطول يصادف احتواءه المفتاح، فيُعاد الفحص على المفتاح نفسه.
  return rows.find((r) => phoneKey(r.phone ?? "") === key) ?? null;
}
