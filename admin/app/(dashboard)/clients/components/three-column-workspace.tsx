import type { ReactNode } from "react";

import { cn } from "@/lib/utils";

/**
 * **الهيكلُ ثلاثيُّ الأعمدة لشاشات العمل في الأدمن.**
 *
 * خالد (١٩ سبتمبر ٢٠٢٦): «سوّي لي component ثلاثة column هنا في الصفحة هذي، لأنّه في
 * عندنا شغل كثير نبغى نسوّيه».
 *
 * وهو أخُ `shared/components/column-layout/ThreeColumnLayout.tsx` لا نسخته: ذاك مقاسُ
 * قراءةٍ لمدونتي (حاويةٌ ١١٢٨ ووسطٌ مسقوفٌ بـ٦٠٠px)، وشاشةُ العمل هنا تحتاج وسطاً
 * يتمدّد بلا سقفٍ لأنّ فيه حقولاً في ثلاثة أعمدة. ولأنّه لا يُستعمل خارج الأدمن،
 * لا يصعد إلى `shared/`.
 *
 * -- السلّم --
 * تحت `lg` عمودٌ واحد: الرفوفُ تنزل تحت المحتوى بدل أن تخنقه. ومن `lg` إلى `xl`
 * عمودان — الوسطُ ورفٌّ واحدٌ يجمع `right` فوق `left`، لأنّ ٥٢٨px من الرفوف على
 * شاشةٍ عرضُها ١٠٢٤ لا تترك للحقول ما يكفي. ومن `xl` ثلاثةُ أعمدةٍ حقيقيّة.
 *
 * والسلّمُ مكتوبٌ بمواضعِ الشبكة (`col-start`/`row-start`) لا بإعادةِ ترتيبٍ بصريّ:
 * ترتيبُ الـDOM يبقى واحداً في كلّ المقاسات، فقارئُ الشاشة ومفتاحُ Tab يمرّان على
 * المحتوى قبل الرفوف مهما ضاقت الشاشة.
 */
export function ThreeColumnWorkspace({
  header,
  left,
  center,
  right,
  className,
}: {
  /** محتوىً بعرض الصفحة فوق الأعمدة — المعاينةُ مثلاً. */
  header?: ReactNode;
  /** الرفُّ الأيسر — السياقُ الذي يُقرأ ولا يُملأ (بياناتُ الطلب). مرّره مغلَّفاً بـ`sticky` إن أردته لاصقاً. */
  left?: ReactNode;
  /** عمودُ العمل — يتمدّد بلا سقفٍ ولا يلتصق. */
  center: ReactNode;
  /** الرفُّ الأيمن — التنقّل. مرّره مغلَّفاً بـ`sticky` إن أردته لاصقاً. */
  right?: ReactNode;
  className?: string;
}) {
  return (
    <div className={cn("space-y-4", className)}>
      {header}
      <div
        className={cn(
          "grid grid-cols-1 gap-4",
          "lg:grid-cols-[minmax(0,1fr)_240px]",
          "xl:grid-cols-[260px_minmax(0,1fr)_240px]",
        )}
      >
        {/**
          * **بلا `items-start`** — الخلايا تمتدّ لارتفاع الصفّ.
          *
          * خالد (١٩ سبتمبر ٢٠٢٦): «العمود اللي على اليمين واللي على اليسار يكونوا
          * ثابتين، واللي في النصّ هو اللي يتحرّك». وكانت الرفوفُ تتحرّك معه رغم
          * `sticky`: مقيسٌ حيّاً — البطاقةُ ٤٩٣px وخليّتُها ٤٩٣px بالضبط. والعنصرُ
          * اللاصقُ لا يلتصق إلّا داخل صندوقٍ **أطولَ منه**؛ `items-start` كان يُنكمش
          * بالخليّة على محتواها فيُلغي المجال. وبالامتداد تصير الخليّةُ بارتفاع العمود
          * الأوسط (١٧٠٨px) فتجد البطاقةُ ١٢٠٠px تنزلق فيها.
          *
          * و`row-span-2` على الوسط في `lg`: هناك الرفّان في عمودٍ واحدٍ صفّاً فوق صفّ،
          * فلولا امتدادُ الوسط عبر الصفّين لبقي الصفُّ الثاني بارتفاع ساكنِه وحده.
          */}
        <div className="min-w-0 lg:col-start-1 lg:row-span-2 lg:row-start-1 xl:col-start-2 xl:row-span-1">{center}</div>
        {right ? <div className="lg:col-start-2 lg:row-start-1 xl:col-start-3 xl:row-start-1">{right}</div> : null}
        {left ? <div className="lg:col-start-2 lg:row-start-2 xl:col-start-1 xl:row-start-1">{left}</div> : null}
      </div>
    </div>
  );
}
