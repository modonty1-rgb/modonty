"use client";

import type { ReactNode } from "react";

/**
 * **رفُّ الفحص — بلا خريطة.**
 *
 * كانت فوقه قائمةُ قفزٍ إلى الأقسام. وسقطت حين صارت الأقسامُ ثلاثة (خالد ١٩ سبتمبر
 * ٢٠٢٦: «كذا معناها النڤيجيشن اللي في العمود اليمين ما نحتاجه»): الوسطُ ٨٣٧px يُرى
 * بتمريرةٍ واحدة، وخريطةٌ لثلاثة بنودٍ تأخذ ١٠٨px ولا توفّر قفزةً — مقيسٌ حيّاً.
 *
 * وكان القسمُ أحدَ عشرَ يوم بُنيت، فكانت الخريطةُ تكسب وقتاً. ثمّ خرج ما لا يُملأ إلى
 * الرفّين، وخرج الربطُ الفنّيُّ إلى راوته — فلم يبقَ ما يُقفز إليه.
 *
 * وسقطت معها ملاحظةُ «بيانات البروفايل يدخلها العميل من الكونسول» (خالد ١٩ سبتمبر
 * ٢٠٢٦): نصٌّ يشرح ما لا يظهر في الشاشة أصلاً — فالحقولُ التي كان يحذّر منها خرجت
 * كلُّها إلى الكونسول، فصار يحذّر من غائب.
 */
export function EditLeftPanel({
  children,
}: {
  /**
   * بطاقاتُ الرفّ — أوراقُ الفحص (صورةُ التوثيق · شارةُ التوثيق · بوّابةُ YMYL).
   *
   * `children` لا خاصّيّةٌ لكلّ بطاقة: الرفُّ يملك التموضعَ اللاصق ولا يعرف ما يُوضع
   * فيه، فبطاقةٌ تُضاف أو تُنقل بلا تعديلٍ هنا.
   */
  children?: ReactNode;
}) {
  return (
    <aside className="space-y-3 lg:sticky lg:top-4">
      {children}

    </aside>
  );
}
