import { chromium } from '@playwright/test';
const base = 'http://localhost:3001';
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1280, height: 1100 } })).newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(`${base}/login`, { waitUntil: 'networkidle' });
await page.fill('input[type="email"]', 'claude-check@modonty.local');
await page.fill('input[type="password"]', 'Mdnty-Local-Check-2026!');
await page.click('button[type="submit"]');
await page.waitForTimeout(5000);
const r = await page.goto(base + '/playbook', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
const t = await page.locator('main').innerText();
console.log('status', r?.status(), 'chars', t.length);
console.log('sections', JSON.stringify(await page.locator('main section[id]').evaluateAll(e => e.map(x => x.id))));
console.log('heads', JSON.stringify(await page.locator('main section[id] h2').evaluateAll(e => e.map(x => x.innerText.replace(/\s+/g,' ').trim())).catch(()=>[])));
console.log('hasWhyHere', t.includes('لماذا نحن هنا'));
console.log('hasPurpose', t.includes('Purpose'), 'headerHasPurpose', (await page.locator('main header').innerText()).includes('Purpose'));
console.log('errs', errs.slice(0,2));
await browser.close();
