/**
 * **سجلُّ القنوات والأحداث — مصدرُ الحقيقة الوحيد للبثّ اللحظيّ.**
 *
 * أُنشئ ٢٠ سبتمبر ٢٠٢٦ بطلب خالد: «إذا اشتغلنا على Pusher نجهّزها، ممكن نحتاجها في
 * حاجات أكثر من النوتيفيكيشن». فالجرسُ أوّلُ مستهلكٍ لا صاحبُ الطبقة: الميزةُ الجديدة
 * تضيف سطراً هنا، ولا تبني بنيةً من جديد — تماماً كما يفعل سجلُّ الإشعارات.
 *
 * ── لماذا `private-` في أوّل كلّ اسم ──
 * القناةُ الخاصّةُ لا يُشترَك فيها إلا بتوقيعٍ من خادمنا (`/api/pusher/auth`)، وبدونها
 * يستطيع أيُّ أحدٍ يعرف اسمَ القناة أن يسمعَ ما يُبثُّ فيها. وإشعارُ الموظّف يحمل عنوانَ
 * مهمّته، فلا يجوز أن يصل زميلاً غيرَه. الاسمُ ليس زينةً: بادئةُ `private-` هي ما يُلزم
 * Pusher باستدعاء مسارِ التصديق أصلاً.
 *
 * ── ولماذا الحمولةُ فقيرة ──
 * ما يُبَثُّ إشارةٌ لا محتوى: «تغيّر شيءٌ يخصّك، اسأل الخادم». والمحتوى يبقى في مونغو —
 * مصدرُ الحقيقة الوحيد. ولو بثثنا نصَّ الإشعار لصار عندنا نسختان لنفس الصفّ، وواحدةٌ
 * منهما تمرّ بطرفٍ ثالث.
 */

