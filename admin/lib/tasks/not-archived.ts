import type { Prisma } from "@prisma/client";

/**
 * «غيرُ مؤرشفة» على مونغو — للمهامّ، كما [NOT_ARCHIVED] للفواتير.
 *
 * `{ archivedAt: null }` وحده يطابق الصفوفَ التي **فيها** الحقلُ وقيمتُه `null` فقط،
 * والصفُّ الذي كُتب قبل إضافة الحقل لا مفتاحَ فيه أصلاً — فيسقط من النتيجة.
 *
 * ── ولماذا صار مصدراً واحداً ──
 * بادجُ «Tasks» في الشريط عدّ المؤرشفةَ معها: قِيس حيّاً ٢٠ سبتمبر ٢٠٢٦ — الشريطُ يقول
 * **٤** واللوحةُ تعرض **١**، والفرقُ ثلاثُ مهامٍّ مؤرشفة. اللوحةُ كانت تحمل الشرطَ
 * وحدَها، والبادجُ كُتب بلا شرط. فالشرطُ هنا ليقرأه العدّادُ واللوحةُ من مكانٍ واحد.
 */
export const TASK_NOT_ARCHIVED: Pick<Prisma.TaskWhereInput, "OR"> = {
  OR: [{ archivedAt: null }, { archivedAt: { isSet: false } }],
};
