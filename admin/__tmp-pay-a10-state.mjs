import { chromium } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
const db = new PrismaClient();
const plan = await db.commercialPlan.findFirst({ where: { name: 'باقة اختبار A10' }, select: { id: true, description: true, badge: true, tier: true, theme: true, displayOrder: true, features: { orderBy: { displayOrder: 'asc' }, select: { displayOrder: true, quantity: true, feature: { select: { name: true, icon: true, unitLabel: true } } } } } });
console.log(JSON.stringify(plan));
const browser = await chromium.launch();
const ctx = await browser.newContext({ storageState: 'C:/tmp/pay-a1-evidence/state.json' });
const page = await ctx.newPage();
await page.goto(`http://localhost:3001/commercial-plans/${plan.id}`, { waitUntil: 'load' }); await page.waitForSelector('main');
console.log('labels:', JSON.stringify(await page.locator('button[aria-label^="تقديم"]').evaluateAll((els) => els.map((e) => [e.getAttribute('aria-label'), e.disabled]))));
await browser.close(); await db.$disconnect();
