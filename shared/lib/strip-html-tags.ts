/**
 * تنظيف نصّ يكتبه مستخدم قبل تخزينه: تُحذف وسوم HTML، ولا يُهرَّب شيء.
 *
 * ── لماذا حذفٌ لا هروب (٣١ أغسطس ٢٠٢٦) ─────────────────────────────────
 * أربع نسخ من دالّة `sanitize` كانت تحوّل `& < > " '` إلى كياناتها **قبل التخزين**
 * (أسئلة العميل في الكونسول وفي مدونتي · سؤال الزائر للشريك · سؤاله من مودو).
 * والخلل في المكان لا في النيّة:
 *
 *  ① الحقول تُعرض `{faq.question}` و`{faq.answer}` داخل JSX، ورياكت يهرّب قيم JSX
 *    تلقائياً. فالهروب المخزَّن يُهرَّب ثانيةً عند العرض ويظهر `&quot;` نصّاً للزائر.
 *  ② `&` كان يُهرَّب أوّلاً، فكل حفظ يضيف طبقة على السابقة:
 *    `&quot;` ← `&amp;quot;` ← `&amp;amp;quot;`. قِيس على الإنتاج: ١٨ صفّاً مصابة،
 *    إحداها بسبع طبقات.
 *  ③ نفس النصّ يُبثّ في `FAQPage` JSON-LD، وكيان HTML لا معنى له في JSON فيصل
 *    جوجل كما هو.
 *
 * الحماية عقدٌ في رياكت لا تحويلٌ نصّي: الخطر محصور في `dangerouslySetInnerHTML`
 * («🔴 SECURITY HOLE: passing untrusted input» — توثيق react.dev)، و`{value}` آمن
 * بالتعريف. فنمنع الوسم نفسه: أي `<...>` يُحذف، ويبقى النصّ نصّاً في كل مستهلك.
 *
 * ⚠️ لا تستعملها على حقلٍ يُحقن بـ`dangerouslySetInnerHTML` — مثل `FAQ.answer`
 * الموسوم في السكيما «can be HTML/rich text» ويُعرض في `/help/faq`. ذاك حقلٌ
 * محتواه HTML مقصود من الأدمن، وله مسار تحريره الخاص.
 */
export function stripHtmlTags(text: string): string {
  return (
    text
      // العنصران اللذان محتواهما كودٌ لا نصّ: يُحذفان بمحتواهما.
      // حذف الوسم وحده كان يترك `alert(1)` نصّاً وسط كلام الزائر (مقيس ٣١ أغسطس)
      // — ليس ثغرةً لأن العرض في `{value}`، لكنه تلويث بلا سبب.
      .replace(/<(script|style)\b[^>]*>[\s\S]*?<\/\1>/gi, "")
      // وبقية الوسوم يُحذف الوسم ويبقى نصّه: «و<b>رحّب</b>» ← «ورحّب».
      .replace(/<[^>]*>/g, "")
      .trim()
  );
}
