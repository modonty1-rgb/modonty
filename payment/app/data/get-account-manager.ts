import "server-only";

import { cacheTag } from "next/cache";

import { db } from "@/lib/db";

/**
 * وسم بيانات الفريق المنشورة.
 *
 * منفصلٌ عن `commercial-catalog`: الأسعار والمزايا تتغيّر بقرارٍ تجاريّ، وبيانات
 * الموظّفين تتغيّر بتوظيفٍ أو نقل — ولا داعي أن يُبطل أحدهما كاش الآخر.
 * والأدمن يرسله عند كل حفظ موظّف.
 */
export const STAFF_TAG = "staff";

/**
 * مسؤول الحساب الذي يُعرض للمشتري — من جدول `Staff` في الأدمن، لا مكتوباً في الكود.
 *
 * ── ليش من الأدمن (خالد ١٥ سبتمبر ٢٠٢٦) ──
 * «بعد التسجيل حتتواصل معاك مديرة الحسابات الأستاذة فاتن». واسمٌ ووجهٌ لإنسانٍ بعينه
 * يقصّر المسافة في مسارٍ تحويله بنكيّ بلا بوّابة تحميه. ولو كُتب في الكود لصار تبديلُ
 * موظّفٍ نشرةً كاملة — وتركُ صفحةٍ حيّة تحوّل عملاء إلى رقمٍ لم يعد لنا.
 *
 * ── التأشيرة وحدها، لا الدور ──
 * كان الشرط `role === SALES` معها، لأن بطاقة «واجهة العميل» في الأدمن كانت لا تظهر
 * لغير المبيعات. وفُتحت لكل الأدوار في اليوم نفسه حين طُلب عرض فريقٍ فيه «مسؤول عملاء»
 * — وهو ليس مبيعات، وجعلُه كذلك ليظهر يفتح له شاشات المبيعات كلّها.
 *
 * فالقارئ هنا يطابق الأدمن: `isPublicContact` تأشيرةٌ صريحة يضعها إنسان، فلا يُنشر
 * أحدٌ بالسهو. و`isActive` معها: من ترك العمل لا يُعرض رقمه ولو بقيت تأشيرته.
 *
 * ── ولا يُعرض إلا بما يكفي ──
 * بلا اسمٍ أو بلا رقمٍ لسوقه ولا للسوق الآخر، لا تُرسم البطاقة: «تواصل مع …» بلا وسيلة
 * تواصلٍ وعدٌ لا يُوفى، وهو أسوأ من غيابه في اللحظة التي يُرسل فيها المشتري مالاً.
 */

/**
 * ── الرقمان يؤدّيان وظيفتين مختلفتين، لا واحدة بلغتين (خالد ١٥ سبتمبر ٢٠٢٦) ──
 *
 * «العميل المصري عنده مشكلة في عدم الثقة مع موظف مصري زيه، فالسند يترسل على الرقم
 * السعودي، ولكن فاتن حتتواصل من الرقم المصري عشان تتابع مع العميل».
 *
 * فالقسمة ليست «رقم قريب ورقم بعيد»:
 *
 * • **إيصال التحويل** يذهب إلى الرقم **السعوديّ** — رقم المؤسّسة. المشتري يرسل صورة
 *   حوالةٍ دفعها للتوّ، وإرسالها إلى رقمٍ محلّيّ يشبه أرقام النصب الشائعة عنده يجعله
 *   يتردّد في آخر خطوة — بعد أن دفع. والرقم السعوديّ هو ما يطابق «مؤسّسة سعودية»
 *   المكتوبة في الصفحة كلّها.
 *
 * • **المتابعة** تأتي من الرقم **المصريّ** — أرخص عليه وأسهل، لكنّ شرطها أن يُعلَن
 *   **قبل** أن يرنّ. رقمٌ مصريّ مجهول يتّصل بعد دفعةٍ بنكية يُقرأ احتيالاً لا خدمة،
 *   فكتابته هنا تحوّل المكالمة من مفاجأةٍ مريبة إلى موعدٍ متوقَّع.
 *
 * ولهذا لا يُسمّيان `primary`/`secondary`: ذاك ترتيبُ أهمية، وهذان دوران.
 */
export type AccountManager = {
  name: string;
  /** اللقب كما يقرأه العميل — «مديرة الحسابات» لا «SALES». */
  title: string | null;
  image: string | null;
  /** الرقم الذي يُرسَل إليه الإيصال — السعوديّ حيثما وُجد. */
  receiptPhone: string;
  /** الرقم الذي ستتّصل منه — يُكتب ولا يُضغط، ويُعلَن قبل أن يرنّ. */
  followUpPhone: string | null;
  followUpNote: string | null;
};

/** أرقام مخزَّنة بأي صياغة — تُنظَّف للرابط، وتُعرض كما كُتبت. */
const digitsOnly = (v: string) => v.replace(/[^\d]/g, "");

export async function getAccountManager(market: "SA" | "EG"): Promise<AccountManager | null> {
  const row = await db.staff
    .findFirst({
      where: {
        isPublicContact: true,
        // الصفوف التي تسبق الحقل تحمل `null` وتُقرأ نشطةً — نفس قراءة الأدمن.
        NOT: { isActive: false },
      },
      select: { name: true, titleAr: true, image: true, phoneSa: true, phoneEg: true },
      orderBy: { updatedAt: "desc" },
    })
    .catch(() => null);

  if (!row?.name) return null;

  const sa = row.phoneSa?.trim() || null;
  const eg = row.phoneEg?.trim() || null;

  /**
   * الإيصال إلى السعوديّ دائماً — هو رقم المؤسّسة. ويسقط على رقم السوق حين لا يوجد
   * سعوديّ أصلاً: مشترٍ بلا طريقٍ لإرسال إيصاله أسوأ من إيصالٍ يصل إلى رقمٍ محلّيّ.
   */
  const receiptPhone = sa ?? (market === "EG" ? eg : null);
  if (!receiptPhone) return null;

  /**
   * رقم المتابعة رقم سوق المشتري — ولا يُكتب إن كان هو نفسه رقم الإيصال: إعلانُ رقمٍ
   * سيتّصل وهو الرقم المكتوب فوقه تكرارٌ يُقرأ خطأً مطبعيّاً.
   */
  const local = market === "EG" ? eg : sa;
  const followUpPhone = local && digitsOnly(local) !== digitsOnly(receiptPhone) ? local : null;

  return {
    name: row.name,
    title: row.titleAr?.trim() || null,
    image: row.image?.trim() || null,
    receiptPhone,
    followUpPhone,
    followUpNote: followUpPhone ? `${row.name.trim().split(" ")[0]} تتواصل معك من هذا الرقم للمتابعة` : null,
  };
}

/** رابط واتساب من رقمٍ بأي صياغة، مع رسالةٍ معبّأة. */
export function whatsappLink(phone: string, text: string): string {
  return `https://wa.me/${digitsOnly(phone)}?text=${encodeURIComponent(text)}`;
}

/**
 * فريق العمل كما يُعرض على صفحة التصفّح — أسماءٌ ووجوهٌ وألقاب، **بلا أرقام**.
 *
 * ── ليش بلا أرقام (قرار خالد ١٥ سبتمبر ٢٠٢٦ بعد نقاش) ──
 * رقمٌ على صفحةٍ عامّة يُجمَع في قوائم الإزعاج خلال أسابيع ولا يُسحَب بعدها. والزائر
 * على الصفحة الأولى لم يقرّر شيئاً بعد، فـ«هذا رقم مديرة حسابك» جوابٌ لسؤالٍ لم يُسأل.
 *
 * فالوظيفتان مفصولتان: هنا **إثباتُ أن وراء الصفحة ناساً** — وجوهٌ وأسماء تُطمئن قبل
 * السعر. وفي صفحة التحويل شخصٌ واحد برقميه، لأن تلك هي لحظة الشكّ: بعد أن دفع.
 *
 * ونفس التأشيرة تحكم الاثنين (`isPublicContact`)، فلا موضعان يتناقضان على من يُنشر.
 */
export type PublicTeamMember = {
  name: string;
  title: string | null;
  image: string | null;
};

export async function getPublicTeam(limit = 6): Promise<PublicTeamMember[]> {
  /**
   * ⚠ `'use cache'` لا `instant = false`.
   *
   * هذا القارئ يُستدعى من الأوفرفيو، وهي **أوّل صفحةٍ في المسار وأغلاها على الأداء**
   * — بُنيت ساكنةً عمداً لتُسلَّم من الحافة. وقراءةٌ غير مكاشة فيها تحجب التصيير
   * المسبق للمسار كلّه («encountered uncached data during prerendering»، قيس ١٥ سبتمبر
   * ٢٠٢٦ على `/[market]`)، فيصير الحلّ الكسول `instant = false` — وهو يُسقط سكونها.
   *
   * والبيانات هنا تحتمل الكاش: أسماءٌ ووجوهٌ وألقاب تتغيّر مرّاتٍ في السنة، لا لكل
   * زائر. فتُكاش تحت وسمها، ويُبطله الأدمن عند حفظ أي موظّف.
   */
  "use cache";
  cacheTag(STAFF_TAG);

  const rows = await db.staff
    .findMany({
      where: { isPublicContact: true, NOT: { isActive: false } },
      select: { name: true, titleAr: true, image: true },
      take: limit,
    })
    .catch(() => []);

  /**
   * بلا اسمٍ لا يُعرض صفّ: بطاقةُ فريقٍ بلا اسم فراغٌ يُقرأ عطلاً.
   *
   * و`flatMap` لا `filter` بحارس نوع: الحارس الذي يفحص `r.name?.trim()` لا يُضيّق
   * `name` من `string | null` في نظر TS (خطأ TS18047 عند `r.name.trim()`)، لأن
   * الشرط على قيمةٍ محسوبة لا على الحقل نفسه. والتصفية والتحويل في خطوةٍ واحدة
   * تُغني عن الحارس أصلاً.
   */
  return rows
    .flatMap((r) => {
      const name = r.name?.trim();
      if (!name) return [];
      return [{ name, title: r.titleAr?.trim() || null, image: r.image?.trim() || null }];
    })
    /**
     * الترتيب بمقارنٍ عربيّ لا بـ`orderBy` في القاعدة: مونغو ترتّب بترتيب البايتات،
     * فتسبق الأسماء اللاتينية العربيةَ كلَّها (قيس ١٥ سبتمبر ٢٠٢٦: `youssef` قبل
     * «روان» و«فاتن»). و`Intl.Collator("ar")` يرتّب الحروف العربية كما تُقرأ.
     *
     * والترتيب ثابتٌ لا يتبع تاريخ التعديل: فريقٌ يقفز ترتيبه بين زيارتين يُقرأ صفحةً
     * غير مستقرّة — وهذا آخر ما تحتاجه صفحةٌ تبني ثقة.
     */
    .sort((a, b) => new Intl.Collator("ar").compare(a.name, b.name));
}
