/**
 * يضمّ رمز الدولة إلى ما كتبه المشتري قبل إرساله (PAY-C3).
 *
 * لماذا وُجد: نموذجا الدفع يعرضان الرمز **لاصقاً ثابتاً** بجانب الحقل ويطلبان الرقم
 * بلا رمزٍ ولا صفر — «5XXXXXXXX» في السعودية و«1XXXXXXXXX» في مصر. فيكتب المشتري
 * `501234567` أو `1012345678`، ثم كان يُرسَل كما هو. و`toE164` على السيرفر يرفضه بحقّ:
 * رقمٌ بلا صفرٍ ولا رمز دولة لا يُعرف بلده (`+966501…` أم `+20501…`؟)، وهو منسّقٌ يخدم
 * السوقين. فكانت الواجهة تطلب الصيغة الوحيدة التي يرفضها السيرفر.
 *
 * والصفحة تعرف سوقها، فهي التي تضمّ الرمز. ولا يُلمس `toE164` لأنه يخدم الأدمن أيضاً
 * حيث تُلصق أرقامٌ من كل شكل، وتوسيعه ليخمّن البلد يُفسده هناك.
 *
 * ── لماذا صار للسوقين بعد أن كان `composeSaPhone` ──
 * كان للسعودية وحدها، ومسار مصر بلا نظيرٍ له — فظلّ يرسل الرقم عارياً. قيس حيّاً على
 * الإنتاج ١٥ سبتمبر ٢٠٢٦: `POST /api/checkout/bank-transfer` بجسمٍ فيه
 * `"phone":"1012345678"` رجع `400 {"error":"invalid-body"}`، والشاشة «تعذّر تسجيل طلبك».
 * أي أن **كل** مشترٍ مصريّ يتبع اللاصق كان يُردّ. ودالّةٌ واحدة تمنع أن يتكرّر الصمت
 * حين يُضاف سوقٌ ثالث.
 *
 * المقيس: «501234567» و«1012345678» ⇐ كانا 400 · «0501234567» و«+966501234567»
 * و«01012345678» ⇐ يمرّان.
 */
export type PhoneMarket = "SA" | "EG";

const DIAL: Record<PhoneMarket, string> = { SA: "966", EG: "20" };

export function composeMarketPhone(input: string, market: PhoneMarket): string {
  const digits = input.replace(/\D/g, "");
  if (!digits) return "";
  const cc = DIAL[market];
  // ما كتبه ومعه الرمز أو الصفر يُترك لـ`toE164` كما هو — هو يفهمهما.
  if (digits.startsWith(`00${cc}`)) return `+${digits.replace(/^00/, "")}`;
  if (digits.startsWith(cc)) return `+${digits}`;
  if (digits.startsWith("0")) return digits;
  return `+${cc}${digits}`;
}
