/**
 * يضمّ رمز الدولة إلى ما كتبه المشتري قبل إرساله (PAY-C3).
 *
 * لماذا وُجد: نموذج الدفع يعرض «+966» لاصقاً ثابتاً ويكتب في الحقل `5XXXXXXXX`، فيكتب
 * المشتري `501234567` — ثم كان يُرسل كما هو. و`toE164` على السيرفر يرفضه بحقّ: رقمٌ بلا
 * صفرٍ ولا رمز دولة لا يُعرف بلده (`+966501…` أم `+20501…`؟)، وهو منسّقٌ يخدم السوقين.
 * فكانت الواجهة تطلب الصيغة الوحيدة التي يرفضها السيرفر — وقيس ذلك حيّاً:
 * «501234567» ⇐ 400 · «0501234567» و«+966501234567» ⇐ يمرّان.
 *
 * والصفحة تعرف سوقها، فهي التي تضمّ الرمز. ولا يُلمس `toE164` لأنه يخدم الأدمن أيضاً
 * حيث تُلصق أرقامٌ من كل شكل، وتوسيعه ليخمّن البلد يُفسده هناك.
 */
export function composeSaPhone(input: string): string {
  const digits = input.replace(/\D/g, "");
  if (!digits) return "";
  // ما كتبه ومعه الرمز أو الصفر يُترك لـ`toE164` كما هو — هو يفهمهما.
  if (digits.startsWith("966") || digits.startsWith("00966")) return `+${digits.replace(/^00/, "")}`;
  if (digits.startsWith("0")) return digits;
  return `+966${digits}`;
}
